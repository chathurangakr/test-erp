<?php

namespace App\Http\Controllers\Accounting;

use App\Actions\Accounting\GenerateJournalReference;
use App\Enums\FiscalPeriodStatus;
use App\Enums\JournalEntryStatus;
use App\Http\Controllers\Controller;
use App\Http\Requests\Accounting\StoreJournalEntryRequest;
use App\Http\Requests\Accounting\UpdateJournalEntryRequest;
use App\Models\Account;
use App\Models\FiscalPeriod;
use App\Models\JournalEntry;
use App\Models\JournalEntryLine;
use App\Support\BusinessClock;
use App\Support\DecimalMath;
use App\Support\SourceDocument;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\ValidationException;
use Inertia\Inertia;
use Inertia\Response;

/**
 * Manual journal entries.
 *
 * A draft may be saved out of balance while someone works on it; only posting applies the
 * balance rule, because only posting puts the entry into the books. Posting, reversing and
 * cancelling live in JournalEntryActionController so the lifecycle is explicit rather than
 * a side effect of saving a form.
 *
 * Manual entries carry no `source_type`, which is what restricts them to accounts that
 * accept manual posting. Entries generated by a business document will name that document
 * and may post to the control accounts it owns.
 */
class JournalEntryController extends Controller
{
    private const PER_PAGE = 25;

    public function __construct(private readonly GenerateJournalReference $references) {}

    public function index(Request $request): Response
    {
        $status = (string) $request->string('status');
        $periodId = $request->integer('fiscal_period_id') ?: null;
        $from = $request->date('from')?->toDateString();
        $to = $request->date('to')?->toDateString();

        $entries = JournalEntry::query()
            ->with(['lines', 'fiscalPeriod:id,name'])
            ->search((string) $request->string('search'))
            ->when($status, fn (Builder $q, string $s) => $q->where('status', $s))
            ->when($periodId, fn (Builder $q, int $id) => $q->where('fiscal_period_id', $id))
            ->when($from, fn (Builder $q, string $d) => $q->whereDate('journal_date', '>=', $d))
            ->when($to, fn (Builder $q, string $d) => $q->whereDate('journal_date', '<=', $d))
            ->orderByDesc('journal_date')
            ->orderByDesc('id')
            ->paginate(self::PER_PAGE)
            ->withQueryString()
            ->through(fn (JournalEntry $entry): array => $this->summarise($entry));

        return Inertia::render('finance/journals/Index', [
            'entries' => $entries,
            'filters' => [
                'search' => (string) $request->string('search'),
                'status' => $status ?: '',
                'fiscal_period_id' => $periodId,
                'from' => $from,
                'to' => $to,
            ],
            'statuses' => JournalEntryStatus::options(),
            'periods' => FiscalPeriod::query()->orderByDesc('start_date')->get(['id', 'name']),
            'currency' => config('accounting.base_currency'),
        ]);
    }

    public function create(): Response
    {
        return Inertia::render('finance/journals/Create', $this->formOptions());
    }

    public function store(StoreJournalEntryRequest $request): RedirectResponse
    {
        $data = $request->validated();
        $period = $this->resolvePeriod($data['journal_date']);

        $entry = DB::transaction(function () use ($data, $period): JournalEntry {
            $entry = JournalEntry::create([
                'journal_number' => $this->references->forJournalEntry(Carbon::parse($data['journal_date'])),
                'journal_date' => $data['journal_date'],
                'fiscal_period_id' => $period->id,
                'description' => $data['description'],
                'status' => JournalEntryStatus::Draft,
                'created_by' => auth()->id(),
            ]);

            $this->writeLines($entry, $data['lines']);

            return $entry;
        });

        Inertia::flash('toast', ['type' => 'success', 'message' => __('Journal entry saved as draft.')]);

        return to_route('journals.show', $entry);
    }

    public function show(JournalEntry $journal): Response
    {
        $journal->load([
            'lines.account:id,code,name,account_type',
            'fiscalPeriod:id,name,status,start_date,end_date',
            'createdBy:id,name',
            'postedBy:id,name',
            'reversedByUser:id,name',
            'reversalOf:id,journal_number',
            'reversedBy:id,journal_number',
        ]);

        return Inertia::render('finance/journals/Show', [
            'entry' => $this->detail($journal),
            'currency' => config('accounting.base_currency'),
        ]);
    }

    public function edit(JournalEntry $journal): Response
    {
        $this->assertEditable($journal);

        $journal->load('lines');

        return Inertia::render('finance/journals/Edit', array_merge($this->formOptions(), [
            'entry' => [
                'id' => $journal->id,
                'journal_number' => $journal->journal_number,
                'journal_date' => $journal->journal_date?->toDateString(),
                'description' => $journal->description,
                'lines' => $journal->lines->map(fn (JournalEntryLine $line): array => [
                    'account_id' => $line->account_id,
                    'description' => $line->description,
                    'debit' => $line->debit,
                    'credit' => $line->credit,
                ])->values(),
            ],
        ]));
    }

    public function update(UpdateJournalEntryRequest $request, JournalEntry $journal): RedirectResponse
    {
        $this->assertEditable($journal);

        $data = $request->validated();
        $period = $this->resolvePeriod($data['journal_date']);

        DB::transaction(function () use ($journal, $data, $period): void {
            $journal->update([
                'journal_date' => $data['journal_date'],
                'fiscal_period_id' => $period->id,
                'description' => $data['description'],
            ]);

            // Safe only because the entry is still a draft — nothing has reached the books.
            $journal->lines()->delete();

            $this->writeLines($journal, $data['lines']);
        });

        Inertia::flash('toast', ['type' => 'success', 'message' => __('Journal entry updated.')]);

        return to_route('journals.show', $journal);
    }

    /**
     * @param  list<array<string, mixed>>  $lines
     */
    private function writeLines(JournalEntry $entry, array $lines): void
    {
        foreach ($lines as $line) {
            $entry->lines()->create([
                'account_id' => $line['account_id'],
                'description' => $line['description'] ?? null,
                'debit' => DecimalMath::cost(DecimalMath::of((string) ($line['debit'] ?? '0'))),
                'credit' => DecimalMath::cost(DecimalMath::of((string) ($line['credit'] ?? '0'))),
            ]);
        }
    }

    /**
     * The open period the journal date falls in.
     *
     * Resolved from the date rather than chosen on the form: a journal belongs to the period
     * containing its date, and letting someone pick a different one would make the period a
     * label rather than a control.
     */
    private function resolvePeriod(string $date): FiscalPeriod
    {
        $period = FiscalPeriod::openFor($date);

        if ($period === null) {
            throw ValidationException::withMessages([
                'journal_date' => __('There is no open fiscal period covering :date.', ['date' => $date]),
            ]);
        }

        return $period;
    }

    private function assertEditable(JournalEntry $entry): void
    {
        if (! $entry->status->isEditable()) {
            throw ValidationException::withMessages([
                'status' => __('Only a draft journal entry can be edited. :reference is :status.', [
                    'reference' => $entry->journal_number,
                    'status' => $entry->status->label(),
                ]),
            ]);
        }
    }

    /**
     * @return array<string, mixed>
     */
    private function formOptions(): array
    {
        return [
            // Only accounts a person may post to by hand. Control accounts and group headers
            // are deliberately absent.
            'accounts' => Account::query()
                ->where('is_active', true)
                ->where('allow_manual_posting', true)
                ->where('is_control_account', false)
                ->orderBy('code')
                ->get(['id', 'code', 'name', 'account_type'])
                ->map(fn (Account $account): array => [
                    'id' => $account->id,
                    'code' => $account->code,
                    'name' => $account->name,
                    'account_type_label' => $account->account_type->label(),
                ]),
            'openPeriods' => FiscalPeriod::query()
                ->where('status', FiscalPeriodStatus::Open)
                ->orderBy('start_date')
                ->get(['id', 'name', 'start_date', 'end_date']),
            'currency' => config('accounting.base_currency'),
        ];
    }

    /**
     * @return array<string, mixed>
     */
    private function summarise(JournalEntry $entry): array
    {
        return [
            'id' => $entry->id,
            'journal_number' => $entry->journal_number,
            'journal_date' => $entry->journal_date?->toDateString(),
            'description' => $entry->description,
            'status' => $entry->status->value,
            'status_label' => $entry->status->label(),
            'fiscal_period' => $entry->fiscalPeriod?->name,
            'debit_total' => $entry->debitTotal(),
            'credit_total' => $entry->creditTotal(),
            'difference' => $entry->difference(),
            'is_balanced' => $entry->isBalanced(),
            'source' => SourceDocument::label($entry->source_type),
        ];
    }

    /**
     * @return array<string, mixed>
     */
    private function detail(JournalEntry $entry): array
    {
        return array_merge($this->summarise($entry), [
            'created_by' => $entry->createdBy?->name,
            'posted_by' => $entry->postedBy?->name,
            'posted_at' => BusinessClock::display($entry->posted_at),
            'reversed_by_user' => $entry->reversedByUser?->name,
            'reversed_at' => BusinessClock::display($entry->reversed_at),
            'reversal_of' => $entry->reversalOf === null ? null : [
                'id' => $entry->reversalOf->id,
                'journal_number' => $entry->reversalOf->journal_number,
            ],
            'reversed_by' => $entry->reversedBy === null ? null : [
                'id' => $entry->reversedBy->id,
                'journal_number' => $entry->reversedBy->journal_number,
            ],
            'period_status' => $entry->fiscalPeriod?->status->label(),
            'can_post' => $entry->status->canPost(),
            'can_edit' => $entry->status->isEditable(),
            'can_cancel' => $entry->status->canCancel(),
            'can_reverse' => $entry->status->canReverse() && ! $entry->isReversed() && ! $entry->isReversal(),
            'lines' => $entry->lines->map(fn (JournalEntryLine $line): array => [
                'id' => $line->id,
                'account_id' => $line->account_id,
                'account_code' => $line->account?->code,
                'account_name' => $line->account?->name,
                'description' => $line->description,
                'debit' => $line->debit,
                'credit' => $line->credit,
            ])->values(),
        ]);
    }
}
