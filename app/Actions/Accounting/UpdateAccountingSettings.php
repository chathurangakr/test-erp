<?php

namespace App\Actions\Accounting;

use App\Enums\AccountType;
use App\Models\Account;
use App\Models\AccountingSetting;
use App\Models\JournalEntry;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\ValidationException;

/**
 * Changes the accounting configuration.
 *
 * The cutover date decides which operational documents generate journals. **Once any
 * system-generated journal exists, it is frozen.** Moving it later would orphan documents
 * that have already been accounted for; moving it earlier would leave a gap of documents
 * that should have been and never will be. Both leave the general ledger and the operational
 * history permanently disagreeing, and neither can be detected afterwards by looking at the
 * books — so the change is refused rather than reasoned about.
 *
 * Setting it for the FIRST time is always allowed: before that no operational journal
 * exists, so there is no history to invalidate.
 *
 * See docs/ACCOUNTING_RULES.md §13.
 */
class UpdateAccountingSettings
{
    /**
     * @param  array{operational_accounting_start_date?: string|null, grni_account_id?: int|null}  $attributes
     */
    public function handle(array $attributes, ?int $userId = null): AccountingSetting
    {
        return DB::transaction(function () use ($attributes, $userId): AccountingSetting {
            $settings = AccountingSetting::query()->orderBy('id')->lockForUpdate()->first()
                ?? new AccountingSetting;

            if (array_key_exists('operational_accounting_start_date', $attributes)) {
                $this->assertCutoverMayChange($settings, $attributes['operational_accounting_start_date']);
                $settings->operational_accounting_start_date = $attributes['operational_accounting_start_date'];
            }

            if (array_key_exists('grni_account_id', $attributes)) {
                $settings->grni_account_id = $this->validLiabilityAccountId(
                    $attributes['grni_account_id'],
                    'grni_account_id',
                    __('Goods Received Not Invoiced'),
                );
            }

            if (array_key_exists('trade_payables_account_id', $attributes)) {
                $settings->trade_payables_account_id = $this->validLiabilityAccountId(
                    $attributes['trade_payables_account_id'],
                    'trade_payables_account_id',
                    __('Trade Payables'),
                );
            }

            $settings->updated_by = $userId ?? auth()->id();
            $settings->save();

            return $settings->refresh();
        });
    }

    private function assertCutoverMayChange(AccountingSetting $settings, ?string $requested): void
    {
        $current = $settings->operational_accounting_start_date?->toDateString();
        $next = $requested === null ? null : Carbon::parse($requested)->toDateString();

        if ($current === $next) {
            return;
        }

        if (! $this->operationalJournalsExist()) {
            return;
        }

        throw ValidationException::withMessages([
            'operational_accounting_start_date' => __('Operational journals already exist, so the accounting start date can no longer be changed. Moving it would leave documents accounted for that should not be, or unaccounted for that should be.'),
        ]);
    }

    /**
     * Whether any journal was generated by an operational document.
     *
     * A manual journal does not count: manual entries are independent of the cutover.
     */
    private function operationalJournalsExist(): bool
    {
        return JournalEntry::query()->whereNotNull('source_type')->exists();
    }

    /**
     * Both control accounts this module configures must be active liabilities.
     */
    private function validLiabilityAccountId(?int $accountId, string $field, string $subject): ?int
    {
        if ($accountId === null) {
            return null;
        }

        $account = Account::find($accountId);

        if ($account === null) {
            throw ValidationException::withMessages([
                $field => __('The selected account does not exist.'),
            ]);
        }

        if (! $account->is_active) {
            throw ValidationException::withMessages([
                $field => __('Account :account is inactive.', ['account' => $account->code]),
            ]);
        }

        if ($account->account_type !== AccountType::Liability) {
            throw ValidationException::withMessages([
                $field => __(':subject must be a liability account; :account is a :type account.', [
                    'subject' => $subject,
                    'account' => $account->code,
                    'type' => $account->account_type->label(),
                ]),
            ]);
        }

        return $account->id;
    }
}
